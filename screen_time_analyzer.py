import pandas as pd
import matplotlib.pyplot as plt
#Screen_time data of one week
data = {
    "Day" : ["Monday", "Tuesday", "Wednesday", "Thursday", "Friday", "Saturday", "Sunday"],
    "Mobile_Hours" : [2,3,2,4,1,3,2],
    "Laptop_Hours" : [1,4,4,3,4,4,2],
    "TV_Hours" : [1,0,2,1,0,1,0],
    "Study_Hours" : [4,5,4,5,5,4,6],
    "Sleep_Hours" : [7,8,8,7,7,8,8]
}
df = pd.DataFrame(data)
print("=====WEEKLY SCREEN-TIME DATA=====")
print(df)

# Weekly Screen_Time Analysis

screen_columns = ["Mobile_Hours", "Laptop_Hours", "TV_Hours"]

df["Total_Screen_Hours"] = df[screen_columns].sum(axis=1)

average_screen_time = df["Total_Screen_Hours"].mean()
total_weekly_screen_time = df["Total_Screen_Hours"].sum()

highest_day = df.loc[df["Total_Screen_Hours"].idxmax(), "Day"]
lowest_day = df.loc[df["Total_Screen_Hours"].idxmax(), "Day"]

average_study = df["Study_Hours"].mean()
average_sleep = df["Sleep_Hours"].mean()

print("\n==========WEEKLY ANALYSIS==========")
print("total weekly screen time:",
     round (total_weekly_screen_time, 2), "hours")

print("Average daily screen time:",
      round(average_screen_time, 2), "hours")

print("Highest screen time day: ", highest_day)
print("Lowest screen time day: ", lowest_day)

print("Average study time: ",
      round(average_study, 2), "hours/day")

print("Average sleep time: ",
      round (average_sleep, 2), "hours/day")

print("===============================")

# Screen time visualisation

plt.figure(figsize=(9,5))

plt.bar(
    df["Day"],
    df["Total_Screen_Hours"]
)

plt.title("Daily Total Screen Time")
plt.xlabel("Day")
plt.ylabel("Screen Time (Hours )")
plt.xticks(rotation=30)

plt.show()

# Study Time VS Screen Time

plt.figure(figsize=(9,5))

plt.plot(
    df["Day"],
    df["Total_Screen_Hours"],
    marker="o",
    label="Screen Time"
)

plt.plot(
    df["Day"],
    df["Study_Hours"],
    marker="o",
    label="Study Time "
)


plt.title("Study Time VS Screen Time")
plt.xlabel("Day")
plt.ylabel("Hours")
plt.xticks(rotation=30)
plt.legend()

plt.show()